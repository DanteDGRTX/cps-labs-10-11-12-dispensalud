DROP TABLE IF EXISTS vet_specialties;
DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS pets;
DROP TABLE IF EXISTS owners;
DROP TABLE IF EXISTS types;
DROP TABLE IF EXISTS specialties;
DROP TABLE IF EXISTS vets;
CREATE TABLE vets(id BIGINT AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(60), last_name VARCHAR(60), email VARCHAR(100));
CREATE TABLE owners(id BIGINT AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(60), last_name VARCHAR(60), city VARCHAR(80));
CREATE TABLE specialties(id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80));
CREATE TABLE types(id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80));
CREATE TABLE pets(id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60), owner_id BIGINT, type_id BIGINT);
CREATE TABLE visits(id BIGINT AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT, visit_date DATE, description VARCHAR(255));
CREATE TABLE vet_specialties(vet_id BIGINT, specialty_id BIGINT, PRIMARY KEY(vet_id, specialty_id));
